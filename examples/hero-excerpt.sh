#!/usr/bin/env bash
# Writes the start-page scenes hero.terminal.yaml (64 columns) and hero-narrow.terminal.yaml
# (50 columns, for phones) from the recorded single-page audit in single-table.cast, and
# builds their cast and SVG. Nothing is run, nothing is reworded: the scenes keep the typed
# command and pick whole lines of the recorded output, with their real colours —
# banner (wide scene only), version line (wide scene only, the narrow one has it in the
# title), Checking, Auditing, the Website Health Report and PASS. Left out are the audit plan,
# the Chrome path and the report file name, whose long lines would wrap. The full recording is
# in the showcase. Called by record.sh; to rebuild by hand:
#
#   examples/hero-excerpt.sh
#
# castwright is called as `castwright`; set CASTWRIGHT to use another command.
set -euo pipefail

castwright="${CASTWRIGHT:-castwright}"
dir="$(cd "$(dirname "$0")" && pwd)"

node - "$dir" <<'JS'
const fs = require('node:fs');
const path = require('node:path');
const dir = process.argv[2];
const [, ...events] = fs.readFileSync(path.join(dir, 'single-table.cast'), 'utf8').trim().split('\n');
const text = events
  .map((line) => JSON.parse(line))
  .filter(([, type]) => type === 'o')
  .map(([, , data]) => data)
  .join('');
const [typed, ...lines] = text.split('\r\n');
// The typed command, split at its options into three shell lines (\ + Enter, continued after
// the "> " prompt), so it does not wrap mid-word in a narrow terminal.
const command = typed.replace(/^\$ /, '');
const parts = command.split(' --');
const commandLines = [
  `${parts[0]} \\`,
  `--${parts.slice(1, 3).join(' --')} \\`,
  `--${parts.slice(3).join(' --')}`,
];
if (commandLines.join(' ').replace(/\\ /g, '') !== command) throw new Error('command split');
const plain = (line) => line.replace(/\x1b\[[0-9;]*m/g, '');
const at = (re) => {
  const i = lines.findIndex((line) => re.test(plain(line)));
  if (i < 0) throw new Error(`single-table.cast: no line matching ${re}`);
  return i;
};
const version = /AuditMySite (v[\d.]+)/.exec(plain(lines[at(/AuditMySite v/)]))[1];
const banner = lines.slice(0, at(/AuditMySite v/));
const report = lines.slice(at(/Website Health Report/), at(/Duration:/) + 1);
const tail = ['', lines[at(/^PASS$/)], ''];
const audit = [lines[at(/^Checking:/)], lines[at(/^Auditing:/)], ...report, ...tail];
const wide = [...banner, lines[at(/AuditMySite v/)], '', ...audit];
const narrow = ['', ...audit];

// castwright unescapes raw output once more after YAML, so backslashes are doubled first.
// Rows: the three command lines plus the output, whose last (empty) line holds the cursor.
const scene = (file, cols, title, output) => {
  const rows = commandLines.length + output.length;
  const yaml = `# Generated by hero-excerpt.sh from single-table.cast: an excerpt of the recorded
# auditmysite ${version.slice(1)} run on casoon.de. Edit hero-excerpt.sh, not this file.
version: 1
terminal:
  title: ${title}
  cols: ${cols}
  rows: ${rows}
  theme: github-dark
steps:
  - run: ${JSON.stringify(commandLines[0])}
  - prompt: "> "
  - run: ${JSON.stringify(commandLines[1])}
  - run: ${JSON.stringify(commandLines[2])}
  - wait: 600
  - output:
      raw: ${JSON.stringify(output.join('\r\n').replace(/\\/g, '\\\\'))}
    delay: 120
  - wait: 5000
`;
  fs.writeFileSync(path.join(dir, file), yaml);
};
scene('hero.terminal.yaml', 64, 'auditmysite casoon.de', wide);
scene('hero-narrow.terminal.yaml', 50, `auditmysite ${version} · casoon.de`, narrow);
JS

for scene in hero hero-narrow; do
  $castwright build "$dir/$scene.terminal.yaml" -o "$dir"
  $castwright build "$dir/$scene.terminal.yaml" --format svg --no-chrome -o "$dir"
done
